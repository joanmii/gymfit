// Lista plana con id estable y texto normalizado para buscar
export const norm = s => String(s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');

export const FOODS = Object.entries(RAW).flatMap(([cat, list]) => list.map(([name, emoji, kcal, protein, carbs, fat, portions, aliases]) => ({
  id: `${cat}:${norm(name).replace(/[^a-z0-9]+/g, '-')}`,
  cat, name, emoji,
  per100: { kcal, protein, carbs, fat },
  portions,
  hay: norm(`${name} ${aliases || ''}`),
})));

export function searchFoods(query, limit = 40) {
  const words = norm(query).split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const q = words.join(' ');
  const scored = [];
  for (const f of FOODS) {
    if (!words.every(w => f.hay.includes(w))) continue;
    const n = norm(f.name);
    const score = n === q ? 0 : n.startsWith(q) ? 1 : n.split(/[\s/()]+/).some(t => t.startsWith(words[0])) ? 2 : 3;
    scored.push([score, n.length, f]);
  }
  return scored.sort((a, b) => a[0] - b[0] || a[1] - b[1]).slice(0, limit).map(x => x[2]);
}

export const foodsByCat = cat => FOODS.filter(f => f.cat === cat);
