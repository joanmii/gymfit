// Recetas predeterminadas. Las cantidades son de la receta entera (sus raciones).
// Ingredientes de foods.js: [alimento, gramos] o [alimento, cantidad, 'u'], que va en
// unidades de su ración (huevos, dientes de ajo, cucharadas…) con botones − / + en la comida.
// «also»: lo que apenas suma calorías (especias, caldo, limón…), para la lista de la compra.
// =========================================================
import { FOODS } from './foods.js';

const byName = new Map(FOODS.map(f => [f.name, f]));

// Alimento listo para la comida, con valores escalados. Si va por unidades guarda la ración (unitG/unitLabel)
export function ingredientItem([name, qty, mode]) {
  const f = byName.get(name);
  if (!f) throw new Error(`Ingrediente desconocido en cookbook.js: ${name}`);
  const [label, ug] = f.portions[0] || ['ración', 100];
  const grams = mode === 'u' ? qty * ug : qty;
  const k = grams / 100, p = f.per100;
  return {
    name: f.name, grams: Math.round(grams),
    kcal: Math.round(p.kcal * k),
    protein: Math.round(p.protein * k * 10) / 10,
    carbs: Math.round(p.carbs * k * 10) / 10,
    fat: Math.round(p.fat * k * 10) / 10,
    ...(mode === 'u' ? { unitG: ug, unitLabel: label } : {}),
  };
}

